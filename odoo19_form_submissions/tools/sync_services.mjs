// Regenerates ../mansas_form_submissions/data/form_service_data.xml from the
// website's single source of truth, src/data/divisions.ts.
// Run from the repository root:  node odoo19_form_submissions/tools/sync_services.mjs
// (Node 22.18+ / 23.6+ runs the .ts import directly.)
// The records are noupdate="1", so names edited in Odoo are kept on upgrade;
// new services are added. Unknown slugs are also created automatically when a
// submission arrives, so running this is only needed for proper labels.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const { divisions } = await import(join(here, '../../src/data/divisions.ts'));
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const xmlId = (slug) => `service_${slug.replace(/[^a-z0-9]/g, '_')}`;

let out = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by odoo19_form_submissions/tools/sync_services.mjs from src/data/divisions.ts. -->\n<odoo noupdate="1">\n';
for (const d of divisions) {
  out += `\n    <!-- ${esc(d.name)} -->\n`;
  d.services.forEach((s, i) => {
    out += `    <record id="${xmlId(s.slug)}" model="mansas.form.service">\n`
      + `        <field name="name">${esc(s.title)}</field>\n`
      + `        <field name="slug">${esc(s.slug)}</field>\n`
      + `        <field name="division">${d.slug}</field>\n`
      + `        <field name="sequence">${(i + 1) * 10}</field>\n`
      + '    </record>\n';
  });
}
out += '</odoo>\n';
const target = join(here, '../mansas_form_submissions/data/form_service_data.xml');
writeFileSync(target, out);
console.log(`Wrote ${divisions.reduce((n, d) => n + d.services.length, 0)} services to ${target}`);
