import json
from datetime import datetime, timedelta, timezone

from odoo import _, api, fields, models

from ..lib.payload import BUDGETS, CHANNELS

STATES = [
    ('new', 'New'),
    ('in_progress', 'In Progress'),
    ('replied', 'Replied'),
    ('closed', 'Closed'),
    ('spam', 'Spam'),
]


class MansasFormSubmission(models.Model):
    """One inquiry sent from the website's contact form.

    Submissions are deliberately independent of CRM leads: nothing here
    depends on the ``crm`` module.
    """
    _name = 'mansas.form.submission'
    _description = 'Website Form Submission'
    _inherit = ['mail.thread', 'mail.activity.mixin']
    _order = 'submitted_at desc, id desc'
    _rec_names_search = ['name', 'contact_name', 'email', 'company']

    name = fields.Char(
        string='Reference', required=True, readonly=True, copy=False, index=True,
        default=lambda self: _('New'))
    active = fields.Boolean(default=True)
    state = fields.Selection(
        STATES, string='Status', required=True, default='new', index=True, tracking=True)
    user_id = fields.Many2one(
        'res.users', string='Assigned To', tracking=True, index=True,
        domain="[('share', '=', False)]")
    company_id = fields.Many2one(
        'res.company', string='Odoo Company', index=True,
        default=lambda self: self.env.company)

    # ── Form fields (website InquiryForm.tsx / schema.ts) ──────────────────
    contact_name = fields.Char(string='Name', required=True, readonly=True)
    email = fields.Char(string='Business Email', required=True, readonly=True, index=True)
    company = fields.Char(string='Company', readonly=True)
    service_ids = fields.Many2many(
        'mansas.form.service', 'mansas_form_submission_service_rel',
        'submission_id', 'service_id', string='Interested In', readonly=True)
    description = fields.Text(string='Project Description', required=True, readonly=True)
    budget = fields.Selection(BUDGETS, string='Budget Range', readonly=True, index=True)
    preferred_contact = fields.Selection(
        CHANNELS, string='Preferred Contact', required=True, default='email', readonly=True)
    phone = fields.Char(string='Phone', readonly=True)

    # ── Submission metadata ────────────────────────────────────────────────
    submission_id = fields.Char(
        string='Submission ID', required=True, readonly=True, copy=False, index=True,
        help="UUID generated by the website form. Used to make retries idempotent.")
    submitted_at = fields.Datetime(
        string='Submitted On', required=True, readonly=True, index=True,
        default=fields.Datetime.now,
        help="When the website received the submission (falls back to the time Odoo received it).")
    form_started_at = fields.Datetime(string='Form Started On', readonly=True)
    fill_duration = fields.Integer(
        string='Time to Complete (s)', readonly=True,
        help="Seconds between the visitor opening the form and the website receiving it.")
    source_website = fields.Char(string='Source Website', readonly=True, index=True)
    source_url = fields.Char(string='Source URL', readonly=True)
    api_key_id = fields.Many2one(
        'mansas.form.api.key', string='Received With Key', readonly=True, ondelete='set null')
    client_ip_hash = fields.Char(
        string='Visitor IP Hash', readonly=True, index=True, groups='base.group_system',
        help="Salted SHA-256 of the visitor's IP, computed by the website. Raw IPs are never sent.")
    user_agent = fields.Char(string='User Agent', readonly=True)
    raw_payload = fields.Text(
        string='Original Submission (JSON)', readonly=True,
        help="The submission object exactly as the website sent it, re-indented for reading.")

    # ── Attribution ────────────────────────────────────────────────────────
    utm_source = fields.Char(string='UTM Source', readonly=True)
    utm_medium = fields.Char(string='UTM Medium', readonly=True)
    utm_campaign = fields.Char(string='UTM Campaign', readonly=True)
    utm_term = fields.Char(string='UTM Term', readonly=True)
    utm_content = fields.Char(string='UTM Content', readonly=True)
    landing_path = fields.Char(string='Landing Page', readonly=True)
    referrer_origin = fields.Char(string='Referrer', readonly=True)

    _submission_id_uniq = models.Constraint(
        'UNIQUE(submission_id)',
        'A submission with this ID has already been received.',
    )

    @api.model_create_multi
    def create(self, vals_list):
        seq = self.env['ir.sequence'].sudo()
        for vals in vals_list:
            if not vals.get('name') or vals['name'] == _('New'):
                vals['name'] = seq.next_by_code('mansas.form.submission') or _('New')
        return super().create(vals_list)

    # ── Status actions ─────────────────────────────────────────────────────
    def action_start(self):
        for rec in self:
            vals = {'state': 'in_progress'}
            if not rec.user_id:
                vals['user_id'] = self.env.user.id
            rec.write(vals)

    def action_mark_replied(self):
        self.write({'state': 'replied'})

    def action_close(self):
        self.write({'state': 'closed'})

    def action_mark_spam(self):
        self.write({'state': 'spam'})

    def action_reset(self):
        self.write({'state': 'new'})

    # ── Ingestion (called by the API controller) ───────────────────────────
    @api.model
    def _prepare_from_api(self, submission, meta, raw_submission, api_key):
        """Build create() values from a parsed payload (see lib/payload.py)."""
        attr = submission['attribution']
        services = self.env['mansas.form.service']._get_or_create_from_slugs(submission['services'])
        started = None
        if submission['started_at_ms']:
            started = datetime.fromtimestamp(
                submission['started_at_ms'] / 1000, tz=timezone.utc).replace(tzinfo=None)
        now = fields.Datetime.now()
        submitted = meta.get('received_at')
        # Trust the website's receipt time only when it is plausible.
        if not submitted or abs(submitted - now) > timedelta(days=1):
            submitted = now
        source_url = meta.get('source_url') or api_key.website_url or False
        return {
            'contact_name': submission['name'],
            'email': submission['email'],
            'company': submission['company'] or False,
            'service_ids': [fields.Command.set(services.ids)],
            'description': submission['description'],
            'budget': submission['budget_key'],
            'preferred_contact': submission['contact'],
            'phone': submission['phone'] or False,
            'submission_id': submission['submission_id'],
            'submitted_at': submitted,
            'form_started_at': started,
            'fill_duration': max(0, int((submitted - started).total_seconds())) if started else 0,
            'source_url': source_url,
            'source_website': _host(source_url) or api_key.name,
            'api_key_id': api_key.id,
            'client_ip_hash': meta.get('client_ip_hash') or False,
            'user_agent': meta.get('user_agent') or False,
            'raw_payload': json.dumps(raw_submission, indent=2, ensure_ascii=False),
            'utm_source': attr.get('utm_source') or False,
            'utm_medium': attr.get('utm_medium') or False,
            'utm_campaign': attr.get('utm_campaign') or False,
            'utm_term': attr.get('utm_term') or False,
            'utm_content': attr.get('utm_content') or False,
            'landing_path': attr.get('landing_path') or False,
            'referrer_origin': attr.get('referrer_origin') or False,
            'company_id': api_key.company_id.id or self.env.company.id,
        }

    @api.model
    def _count_recent(self, domain, seconds=60):
        # create_date is set from the transaction clock, so compare against it too.
        since = self.env.cr.now() - timedelta(seconds=seconds)
        return self.sudo().with_context(active_test=False).search_count(
            domain + [('create_date', '>=', since)])


def _host(url):
    if not url:
        return ''
    rest = url.split('://', 1)[-1]
    return rest.split('/', 1)[0].split('?', 1)[0].split('#', 1)[0].lower()
